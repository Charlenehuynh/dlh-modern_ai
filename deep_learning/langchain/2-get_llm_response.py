#!/usr/bin/env python3
"""Generate a response from a LangChain LLM"""


def get_response(llm, prompt):
    """
    Generates a response from a loaded language model.

    Args:
        llm: an instance of a LangChain LLM
        prompt: string containing the question or instruction

    Returns:
        AIMessage: the full response object generated by the LLM
    """
    return llm.invoke(prompt)
